  function resolveLocale() {
    let stored = null;
    try { stored = localStorage.getItem(STORAGE_KEY); } catch {}
    return LOCALES.includes(stored) ? stored : DEFAULT_LOCALE;
  }

  function message(locale, key, vars = {}) {
    let value;
    if (semantic[locale] && Object.prototype.hasOwnProperty.call(semantic[locale], key)) {
      value = semantic[locale][key];
    } else if (locale === 'zh-CN') {
      value = zh[key] || key;
    } else {
      value = key;
    }
    return String(value).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
  }

  function patterned(locale, text) {
    if (locale !== 'zh-CN') return text;
    let m = text.match(/^(\d+)–(\d+) of (\d+) results$/);
    if (m) return `第 ${m[1]}–${m[2]} 项，共 ${m[3]} 项`;
    m = text.match(/^0 results$/);
    if (m) return '0 项结果';
    m = text.match(/^(\d+)–(\d+) of (\d+) issues$/);
    if (m) return `第 ${m[1]}–${m[2]} 项，共 ${m[3]} 个问题`;
    m = text.match(/^(\d+)–(\d+) of (\d+) sources$/);
    if (m) return `第 ${m[1]}–${m[2]} 项，共 ${m[3]} 个来源`;
    m = text.match(/^Run (run_[A-Za-z0-9_-]+)$/);
    if (m) return `运行 ${m[1]}`;
    m = text.match(/^Stage (\d+) · (.+)$/);
    if (m) return `阶段 ${m[1]} · ${m[2]}`;
    m = text.match(/^(\d+) binding\(s\)( · fallback → .+)?$/);
    if (m) return `${m[1]} 个绑定${m[2] ? m[2].replace(' · fallback → ', ' · 回退 → ') : ''}`;
    m = text.match(/^(\d+) total · (\d+) non-selectable$/);
    if (m) return `共 ${m[1]} 个 · ${m[2]} 个不可选择`;
    m = text.match(/^(Current|Rollback) · (listening|down)$/);
    if (m) return `${message(locale, m[1])} · ${message(locale, m[2])}`;
    return text;
  }

  function translateText(locale, raw) {
    if (locale !== 'zh-CN' || !raw || !raw.trim()) return raw;
    const leading = raw.match(/^\s*/)?.[0] || '';
    const trailing = raw.match(/\s*$/)?.[0] || '';
    const core = raw.trim();
    const exact = zh[core];
    const translated = exact || patterned(locale, core);
    return leading + translated + trailing;
  }

  function shouldSkipText(node) {
    const parent = node.parentElement;
    if (!parent) return true;
    return !!parent.closest('script,style,pre,code,.mono,.path,[data-no-i18n]');
  }

  function localizeTree(root, locale) {
    if (!root) return;
    if (locale === 'zh-CN') {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      const nodes = [];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      for (const node of nodes) {
        if (shouldSkipText(node)) continue;
        const translated = translateText(locale, node.nodeValue);
        if (translated !== node.nodeValue) node.nodeValue = translated;
      }
      for (const element of root.querySelectorAll?.('[placeholder],[aria-label],[title]') || []) {
        for (const attr of ['placeholder', 'aria-label', 'title']) {
          if (!element.hasAttribute(attr)) continue;
          const current = element.getAttribute(attr);
          if (!current || element.matches('.path,[data-no-i18n]')) continue;
          const translated = message(locale, current);
          if (translated !== current) element.setAttribute(attr, translated);
        }
      }
    }
  }

  function applyStatic(root, locale) {
    document.documentElement.lang = locale;
    for (const node of root.querySelectorAll('[data-i18n]')) {
      const value = message(locale, node.dataset.i18n);
      if (node.textContent !== value) node.textContent = value;
    }
    for (const node of root.querySelectorAll('[data-i18n-aria-label]')) {
      const value = message(locale, node.dataset.i18nAriaLabel);
      if (node.getAttribute('aria-label') !== value) node.setAttribute('aria-label', value);
    }
    for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
      const value = message(locale, node.dataset.i18nPlaceholder);
      if (node.getAttribute('placeholder') !== value) node.setAttribute('placeholder', value);
    }
  }

  window.SCP_I18N = {
    STORAGE_KEY,
    DEFAULT_LOCALE,
    LOCALES,
    resolveLocale,
    message,
    translateText,
    localizeTree,
    applyStatic
  };
